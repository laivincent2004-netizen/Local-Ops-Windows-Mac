/**
 * Translate a semantic key and safely interpolate `{variable}` placeholders.
 * Missing variables remain visible, which makes integration mistakes easy to
 * spot without ever treating a value as HTML.
 */
export function t(key, vars = {}) {
  const normalizedKey = String(key ?? '');
  const primary = translations[currentLanguage] || translations[DEFAULT_LANGUAGE];
  const template = primary[normalizedKey]
    ?? translations[DEFAULT_LANGUAGE][normalizedKey]
    ?? normalizedKey;
  const values = vars && typeof vars === 'object' ? vars : {};
  return String(template).replace(/\{([A-Za-z0-9_.-]+)\}/g, (match, name) => {
    if (!Object.prototype.hasOwnProperty.call(values, name)) return match;
    const value = values[name];
    return value == null ? '' : String(value);
  });
}

/**
 * Translate a small allowlist of server-authored labels. Unknown values pass
 * through byte-for-byte so user names, paths, commands, and logs are untouched.
 */
export function translateKnownText(value) {
  if (typeof value !== 'string' || currentLanguage !== 'en') return value;
  const exact = KNOWN_TEXT_EN.get(value);
  if (exact !== undefined) return exact;
  for (const [pattern, translate] of KNOWN_TEXT_EN_PATTERNS) {
    const match = value.match(pattern);
    if (match) return translate(match);
  }
  return value;
}

export function getLanguage() {
  return currentLanguage;
}

/**
 * Set `zh` or `en`. Invalid values are ignored and the current language is
 * returned. The choice is per-browser and survives reloads.
 */
export function setLanguage(language) {
  const next = String(language || '').toLowerCase();
  if (!SUPPORTED_LANGUAGES.has(next)) return currentLanguage;

  const changed = next !== currentLanguage;
  currentLanguage = next;
  try {
    globalThis.localStorage?.setItem(LANGUAGE_STORAGE_KEY, currentLanguage);
  } catch (_) {
    // A blocked/private localStorage must not prevent an in-memory switch.
  }
  setDocumentLanguage(currentLanguage);

  if (typeof document !== 'undefined') applyStaticTranslations(document);
  if (changed) {
    for (const listener of [...listeners]) {
      try {
        listener(currentLanguage);
      } catch (error) {
        // One subscriber must not prevent the remaining UI from rerendering.
        globalThis.setTimeout?.(() => { throw error; }, 0);
      }
    }
  }
  return currentLanguage;
}

export function toggleLanguage() {
  return setLanguage(currentLanguage === 'zh' ? 'en' : 'zh');
}

/** Subscribe to language changes. Returns an unsubscribe function. */
export function subscribeLanguage(listener) {
  if (typeof listener !== 'function') return () => {};
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function translationVars(element) {
  const raw = element.getAttribute('data-i18n-vars');
  if (!raw) return {};
  try {
    const value = JSON.parse(raw);
    return value && typeof value === 'object' && !Array.isArray(value) ? value : {};
  } catch (_) {
    return {};
  }
}

function matchingElements(root, selector) {
  const result = [];
  if (root && typeof root.matches === 'function' && root.matches(selector)) {
    result.push(root);
  }
  if (root && typeof root.querySelectorAll === 'function') {
    result.push(...root.querySelectorAll(selector));
  }
  return result;
}

/**
 * Apply declarative translations. Supported attributes:
 *   data-i18n, data-i18n-placeholder, data-i18n-title,
 *   data-i18n-aria-label, data-i18n-alt, data-i18n-value,
 *   data-i18n-content
 * Optional data-i18n-vars must be a JSON object. Text uses textContent only;
 * this function intentionally never uses innerHTML.
 */
export function applyStaticTranslations(root = document) {
  if (!root) return;
  const descriptors = [
    ['data-i18n', null],
    ['data-i18n-placeholder', 'placeholder'],
    ['data-i18n-title', 'title'],
    ['data-i18n-aria-label', 'aria-label'],
    ['data-i18n-alt', 'alt'],
    ['data-i18n-value', 'value'],
    ['data-i18n-content', 'content'],
  ];

  for (const [sourceAttribute, targetAttribute] of descriptors) {
    for (const element of matchingElements(root, `[${sourceAttribute}]`)) {
      const key = element.getAttribute(sourceAttribute);
      if (!key) continue;
      const value = t(key, translationVars(element));
      if (targetAttribute) element.setAttribute(targetAttribute, value);
      else element.textContent = value;
    }
  }
}

// Keep another open Console tab in sync without making storage mandatory.
if (typeof globalThis.addEventListener === 'function') {
  globalThis.addEventListener('storage', event => {
    if (event.key === LANGUAGE_STORAGE_KEY && SUPPORTED_LANGUAGES.has(event.newValue)) {
      setLanguage(event.newValue);
    }
  });
}
